const assert=require('node:assert/strict');
const {MapReportSelection:s}=require('../../scripts/benchmarks/map_report_selection.js');
const states=[1,2,3].flatMap(run=>['initial','update000010','final'].map(label=>({run,label})));
assert.deepEqual(s.endpoints(states).map(x=>x.index),[0,2,3,5,6,8]);
assert.deepEqual(s.runs([1,2,3],states[0],states[5],false),[1,2]);
assert.deepEqual(s.runs([1,2,3],states[0],states[2],false),[1]);
assert.deepEqual(s.runs([1,2,3],states[0],states[2],true),[1,2,3]);
assert.deepEqual(s.snapshots(states,[1,2,3],states[0],states[5],false),[states[0],states[5]]);
assert.deepEqual(s.snapshots(states,[1,2,3],states[0],states[5],true),[states[0],states[5],states[8]]);
assert.deepEqual(s.snapshots(states,[1,2,3],states[0],states[3],true),[states[0],states[3],states[6]]);
assert.deepEqual(s.snapshots(states,[1,2,3],states[0],states[0],false),[states[0]]);
console.log('Map report selection: endpoints, all/A-B scope, same-run and mixed-phase cases passed');
