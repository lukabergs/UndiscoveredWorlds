"""Generate declared process access from measured access reports.

    python scripts/evaluation/process_access.py REPORT.json [REPORT.json ...] [--check]

Reports come from the read-tracking analysis build (`-DUW_TRACK_FIELD_READS=ON`):

    world_pipeline generate ... --audit-access --access-report REPORT.json

Each process's declared reads and writes become the union over all reports, and a
process is marked stochastic when any report saw it draw from the shared random
generator. The result is written to src/pipeline/world_process_access.inc. Reads are
only as complete as the code paths the reports exercised, and a write is seen only
when it changes a value: small or short worlds leave out lakes, deltas and scenario
fields. Stored sets accumulate (runs/reports/phase4-access, phase4b-access and phase4c-access
are read together; phase4c is the four small runs measured after the float steps). The quick set, phase4b-access, is five runs at seed 1: tectonics
with `--plume-count 4 --progressive-rifting on`, earth-climate, imported-world and
procedural-world with --social on 128 x 64, and one procedural world with --social at
the default size, the only run that exercises the lake, delta and wetland writes.
The set erosion-a-access is one minimal eroded-world run at seed 1 (128 x 64, --duration 50,
climate 32/2), measured in erosion plan step A4 for hydrology.flow_routing and terrain.fluvial_erosion.
The set erosion-b-access holds one minimal eroded-world run per Phase B step that changed a
process's access (b1-eroded-world.json, ...), each measured at that step's commit and kept.
The set erosion-c-access does the same for Phase C (c1-eroded-world.json, c1-earth-hydrology.json, ...);
Phase C's steps also measure earth-hydrology at 128 x 64 (Earth maps and lakes, climate 32/2) when
they change a process of that recipe.
The set erosion-d-access holds the Phase D runs (d1-eroded-world.json: the engine's rock uplift rate,
written by geology.plate_tectonics and read by terrain.fluvial_erosion).
A process that no report ran gets no declaration.
`--check` exits 1 when the file would change instead of writing it.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'src/pipeline/world_process_access.inc'
CATALOGUE = ROOT / 'src/core/world/world_fields.cpp'


def table_enumerators():
    """'component.name' -> TableId enumerator, from the table specs in the catalogue."""
    text = CATALOGUE.read_text(encoding='utf-8')
    pattern = re.compile(r'\{\s*TableId::(\w+),\s*Component::(\w+),\s*"(\w+)"')
    return {f'{component}.{name}': enumerator for enumerator, component, name in pattern.findall(text)}


def enumerator(qualified, tables=None):
    """Field enumerators equal the field name; table enumerators come from the catalogue."""
    if tables is not None:
        if qualified not in tables:
            raise SystemExit(f'Unknown table {qualified}; not in {CATALOGUE.relative_to(ROOT)}')
        return tables[qualified]
    return qualified.split('.', 1)[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('reports', nargs='+', type=Path)
    parser.add_argument('--check', action='store_true', help='Fail if the generated file differs instead of writing it')
    args = parser.parse_args()

    processes = {}
    sources = []
    for path in args.reports:
        report = json.loads(path.read_text(encoding='utf-8'))
        if report.get('schema') != 'uw-access-report/v1':
            raise SystemExit(f'{path}: not an access report')
        if not report.get('tracking_reads'):
            raise SystemExit(f'{path}: reads were not tracked; use the UW_TRACK_FIELD_READS build')
        sources.append(f'{report["recipe"]} ({path.name})')
        for step in report['steps']:
            if not step['measured']:
                raise SystemExit(f'{path}: step {step["label"]} was not audited; pass --audit-access')
            entry = processes.setdefault(step['process'], {'reads': set(), 'writes': set(), 'table_reads': set(),
                                                           'table_writes': set(), 'random': False})
            for key in ('reads', 'writes', 'table_reads', 'table_writes'):
                entry[key].update(step[key])
            entry['random'] = entry['random'] or step['drew_random']

    lines = [
        '// Measured process access. Generated by scripts/evaluation/process_access.py from',
        '// access reports of the read-tracking analysis build; do not edit by hand.',
        '// Reports: ' + '; '.join(sources),
        '#pragma once',
        '',
        '#include <string_view>',
        '',
        'inline void applymeasuredaccess(WorldProcessDefinition& process)',
        '{',
        '    using F = worldmodel::FieldId;',
        '    using T = worldmodel::TableId;',
        '    const std::string_view id = process.id;',
    ]

    tables = table_enumerators()

    def initializer(prefix, names):
        if not names:
            return '{}'
        lookup = tables if prefix == 'T' else None
        return '{ ' + ', '.join(f'{prefix}::{enumerator(name, lookup)}' for name in sorted(names)) + ' }'

    for process_id in sorted(processes):
        entry = processes[process_id]
        lines += [
            f'    if (id == "{process_id}")',
            '    {',
            f'        process.reads = {initializer("F", entry["reads"])};',
            f'        process.writes = {initializer("F", entry["writes"])};',
            f'        process.tablereads = {initializer("T", entry["table_reads"])};',
            f'        process.tablewrites = {initializer("T", entry["table_writes"])};',
        ]
        if entry['random']:
            lines.append('        process.stochastic = true;')
        lines += ['        return;', '    }']
    lines += ['}', '']
    text = '\n'.join(lines)

    if args.check:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
        if current != text:
            print(f'{OUTPUT.relative_to(ROOT)} is out of date')
            sys.exit(1)
        print(f'{OUTPUT.relative_to(ROOT)} is current')
        return
    OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'Wrote {OUTPUT.relative_to(ROOT)}: {len(processes)} processes from {len(args.reports)} report(s)')


if __name__ == '__main__':
    main()
