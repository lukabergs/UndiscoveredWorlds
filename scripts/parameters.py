"""Generate the parameter headers of the simulation modules from configs/parameters/<module>.json.

    uv run --offline scripts/parameters.py           write the headers
    uv run --offline scripts/parameters.py --check   exit 1 if a tracked header differs from its JSON

A file configs/parameters/<module>.json holds the default of every tunable value of one module:

    {"module": "terrain", "namespace": "tuning::terrain",
     "header": "src/simulations/terrain/terrain_parameters.hpp",
     "types": {"oceanridges.ridge_angle_search_distance": "short"},
     "parameters": {"oceanridges": {"grid_size": 16, "point_shift_fractal_value_mod": 0.2}}}

A value is bool (true, false), int (a whole number) or float (a number with a point or an
exponent) unless "types" names it as short, double or float. The header declares each value
as a variable <namespace>::<group>::<camelCaseName> initialised with the number exactly as
written here, and lists them for the parameter registry (core/parameters.hpp) under the name
<module>.<group>.<key>, which is the name `world_pipeline run --set name=value` takes and
the bundle manifest records. The headers are tracked; edit the JSON and run this script.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'configs/parameters'
TYPES = ('bool', 'short', 'int', 'float', 'double')


class Number(str):
    """A JSON number kept as its text."""


def camel(key):
    parts = key.split('_')
    return parts[0] + ''.join(part[:1].upper() + part[1:] for part in parts[1:])


def value_type(value, declared):
    if isinstance(value, bool):
        inferred = 'bool'
    elif isinstance(value, Number):
        inferred = 'float' if re.search(r'[.eE]', value) else 'int'
    else:
        raise SystemExit(f'unsupported value {value!r}')
    kind = declared or inferred
    if kind not in TYPES or (kind == 'bool') != (inferred == 'bool') or (inferred == 'float' and kind in ('short', 'int')):
        raise SystemExit(f'value {value!r} cannot be {kind}')
    return kind


def literal(value, kind):
    if kind == 'bool':
        return 'true' if value else 'false'
    if kind in ('short', 'int'):
        return str(value)
    text = str(value) if re.search(r'[.eE]', value) else f'{value}.0'
    return text + ('f' if kind == 'float' else '')


def render(path):
    config = json.loads(path.read_text(encoding='utf-8'), parse_float=Number, parse_int=Number)
    module, namespace, types = config['module'], config['namespace'], config.get('types', {})
    lines = [f'// Generated by scripts/parameters.py from configs/parameters/{path.name}; do not edit.', '#pragma once', '',
             '#include <vector>', '', '#include "core/parameters.hpp"', '', f'namespace {namespace}', '{']
    entries = []
    unused = set(types)
    for group, values in config['parameters'].items():
        lines += [f'namespace {group}', '{']
        for key, value in values.items():
            if not re.fullmatch(r'[a-z][a-z0-9]*(_[a-z0-9]+)*', key):
                raise SystemExit(f'{path.name}: {group}.{key} is not snake_case')
            kind = value_type(value, types.get(f'{group}.{key}'))
            unused.discard(f'{group}.{key}')
            lines.append(f'inline {kind} {camel(key)} = {literal(value, kind)};')
            entries.append(f'        {{ "{module}.{group}.{key}", &{group}::{camel(key)} }},')
        lines += ['}', '']
    if unused:
        raise SystemExit(f'{path.name}: types for unknown values {sorted(unused)}')
    lines += ['// Every value above, by its recipe name.', 'inline const std::vector<parameters::Entry>& parameterentries()', '{',
              '    static const std::vector<parameters::Entry> entries = {'] + entries + ['    };', '    return entries;', '}', '}', '']
    return ROOT / config['header'], '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    stale = []
    for path in sorted(DIRECTORY.glob('*.json')):
        header, text = render(path)
        current = header.read_text(encoding='utf-8').replace('\r\n', '\n') if header.exists() else None
        if current == text:
            continue
        if arguments.check:
            stale.append(header.relative_to(ROOT).as_posix())
        else:
            header.write_text(text, encoding='utf-8', newline='\n')
            print(f'wrote {header.relative_to(ROOT).as_posix()}')
    if stale:
        print('Parameter headers differ from configs/parameters: ' + ', '.join(stale))
        return 1
    if arguments.check:
        print('Parameter headers are current.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
