"""Generate the dependency-free C++ equivalent of climate-palettes.json."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
d=json.loads((ROOT/'configs/climate-palettes.json').read_text())
lines=['// Generated by scripts/benchmarks/generate-climate-palette-header.py; do not hand edit.',
       '#pragma once', '#include <algorithm>', '#include <array>', '#include <cmath>',
       'namespace climatepalette {', 'struct Stop { double position; std::array<unsigned char, 3> rgb; };']
for name in ('positive','signed'):
    symbol='signedStops' if name=='signed' else 'positiveStops'
    rows=',\n'.join('    Stop{'+str(t)+', {'+', '.join(map(str,c))+'}}' for t,c in d[name])
    lines.append(f'inline constexpr std::array<Stop, {len(d[name])}> {symbol} = {{{{\n{rows}\n}}}};')
for name,(lo,hi) in d['scales'].items():
    symbol='field_'+name
    lines.extend([f'inline constexpr double {symbol}_low = {float(lo)};',f'inline constexpr double {symbol}_high = {float(hi)};'])
lines += ['inline std::array<unsigned char, 3> colour(double value, double low, double high, bool isSigned) {',
          '    if (!std::isfinite(value) || !(high > low)) return {0, 0, 0};',
          '    double t = isSigned && low < 0 && high > 0 ? (value <= 0 ? .5*(value-low)/(-low) : .5+.5*value/high) : (value-low)/(high-low);',
          '    t = std::clamp(t, 0.0, 1.0);',
          '    const auto& stops = isSigned ? signedStops : positiveStops;',
          '    for (std::size_t i=1; i<stops.size(); ++i) if (t <= stops[i].position) {',
          '        const double f=(t-stops[i-1].position)/(stops[i].position-stops[i-1].position);',
          '        std::array<unsigned char, 3> result{};',
          '        for (int c=0; c<3; ++c) result[c]=static_cast<unsigned char>(std::floor(stops[i-1].rgb[c]+f*(int(stops[i].rgb[c])-int(stops[i-1].rgb[c]))+.5));',
          '        return result;', '    }', '    return stops.back().rgb;', '}', '}']
text='\n'.join(lines)+'\n';p=ROOT/'src/validation/climate/climate_palette.hpp'
args=argparse.ArgumentParser();args.add_argument('--check',action='store_true');options=args.parse_args()
if options.check:
    if p.read_text()!=text:raise SystemExit('Generated palette header is stale')
else:p.write_text(text)
